
class Learn_3 {

    public static void main(String[] args) {
        // For Loop
        System.out.println("For Loop in Java");
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        // While Loop 
        System.out.println("While Loop in Java");
        int i = 0;
        while (i <= 5) {
            System.out.println(i);
            i++;
        }
    }
}
